import type { Metadata } from "next";
import { redirect } from "next/navigation";

import { ReportCrawlerContent } from "@/components/report/ReportCrawlerContent";
import { ReportJsonLd } from "@/components/report/ReportJsonLd";
import { isIndexableReportRouteParam } from "@/lib/report-indexing";
import { buildReportMetadata } from "@/lib/report-seo";
import { getCachedReportRouteBundle } from "@/lib/report-server-cache";
import { canGenerateReportMetadata } from "@/lib/report-seo-loader";
import {
  isDemoReportRouteParam,
  resolveReportRouteParam,
  shouldRedirectToCanonicalSlug,
} from "@/lib/report-route";
import { getRequestSiteUrl } from "@/lib/request-site-url";
import { buildPageMetadata } from "@/lib/seo";
import { isSupabaseConfigured } from "@/lib/supabase-server";

export const dynamic = "force-dynamic";

type ReportLayoutProps = {
  children: React.ReactNode;
  params: Promise<{ id: string }>;
};

export async function generateMetadata({
  params,
}: {
  params: Promise<{ id: string }>;
}): Promise<Metadata> {
  const { id } = await params;
  const siteUrl = getRequestSiteUrl();

  if (!canGenerateReportMetadata(id)) {
    return buildPageMetadata({
      title: "Report not found",
      description: "This report link is invalid or has expired.",
      path: `/report/${id}`,
      index: false,
    });
  }

  if (!isDemoReportRouteParam(id) && !isSupabaseConfigured()) {
    return buildPageMetadata({
      title: "UX Report",
      description: "UX clarity report generated by Klynt.",
      path: `/report/${id}`,
      index: false,
    });
  }

  try {
    const { resolved, report } = await getCachedReportRouteBundle(id);

    if (!resolved || !report) {
      return buildPageMetadata({
        title: "UX Report",
        description: "UX clarity report generated by Klynt.",
        path: `/report/${id}`,
        index: false,
      });
    }

    return buildReportMetadata(resolved.slug, report, siteUrl);
  } catch {
    return buildPageMetadata({
      title: "UX Report",
      description: "UX clarity report generated by Klynt.",
      path: `/report/${id}`,
      index: false,
    });
  }
}

export default async function ReportLayout({
  children,
  params,
}: ReportLayoutProps) {
  const { id } = await params;
  const siteUrl = getRequestSiteUrl();
  const resolved = await resolveReportRouteParam(id);

  if (resolved && shouldRedirectToCanonicalSlug(id, resolved)) {
    redirect(resolved.path);
  }

  if (!isIndexableReportRouteParam(id) || !canGenerateReportMetadata(id)) {
    return children;
  }

  if (!isDemoReportRouteParam(id) && !isSupabaseConfigured()) {
    return children;
  }

  try {
    const { resolved: cachedResolved, report } = await getCachedReportRouteBundle(id);

    if (!report || !cachedResolved) {
      return children;
    }

    return (
      <>
        <ReportJsonLd routeSlug={cachedResolved.slug} report={report} siteUrl={siteUrl} />
        <ReportCrawlerContent report={report} />
        {children}
      </>
    );
  } catch {
    return children;
  }
}
